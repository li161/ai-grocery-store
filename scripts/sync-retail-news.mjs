import { mkdir, writeFile } from 'node:fs/promises'

const FEEDS = [
  {name:'Google News · AI Shopping',url:'https://news.google.com/rss/search?q=AI+shopping+assistant+retail+agentic+commerce+when%3A7d&hl=en-US&gl=US&ceid=US:en',lane:'AI 导购'},
  {name:'Google News · Retail AI',url:'https://news.google.com/rss/search?q=retail+AI+agent+inventory+shopping+when%3A7d&hl=en-US&gl=US&ceid=US:en',lane:'零售运营'},
  {name:'Google News · China Retail AI',url:'https://news.google.com/rss/search?q=China+retail+AI+shopping+Qwen+Taobao+JD+when%3A14d&hl=en-US&gl=US&ceid=US:en',lane:'中国零售'},
  {name:'Google News · Agentic Commerce',url:'https://news.google.com/rss/search?q=%22agentic+commerce%22+shopping+retail+when%3A14d&hl=en-US&gl=US&ceid=US:en',lane:'Agentic Commerce'}
]

const seedFile = new URL('../src/data/retailNews.generated.js', import.meta.url)

function decode(value = '') {
  return value.replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1')
    .replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'")
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
}

function tag(xml, name) {
  const re = new RegExp('<' + name + '(?:\\s[^>]*)?>([\\s\\S]*?)</' + name + '>', 'i')
  return decode(xml.match(re)?.[1]?.trim() || '')
}

function guessTags(title = '') {
  const rules = [
    ['AI 导购', /shopping assistant|shopping agent|导购|购物助手/i],
    ['Agent', /agentic|agent/i],
    ['支付', /checkout|payment|支付/i],
    ['库存', /inventory|stock|supply chain|库存|供应链/i],
    ['推荐', /recommend|recommendation|推荐/i],
    ['零售App', /app|mobile|应用/i]
  ]
  return rules.filter(([, re]) => re.test(title)).map(([name]) => name)
}

async function fetchFeed(feed) {
  try {
    const response = await fetch(feed.url, {headers:{'user-agent':'ai-grocery-store-retail-sync/1.0'}})
    if (!response.ok) throw new Error('HTTP ' + response.status)
    const xml = await response.text()
    return [...xml.matchAll(/<item>([\s\S]*?)<\/item>/gi)].slice(0,15).map((m,index) => {
      const raw = m[1], title = tag(raw,'title'), link = tag(raw,'link'), pubDate = tag(raw,'pubDate')
      if (!title || !link) return null
      const parsed = Date.parse(pubDate)
      return {
        id:'feed-' + feed.name.replace(/[^a-z0-9]+/gi,'-').toLowerCase() + '-' + index + '-' + (parsed || Date.now()),
        source:feed.name,
        date:Number.isNaN(parsed) ? new Date().toISOString().slice(0,10) : new Date(parsed).toISOString().slice(0,10),
        lane:feed.lane,
        title,
        summary:'自动同步情报：打开原文查看完整报道与上下文。',
        impact:'进入零售 AI 雷达，等待进一步人工研判。',
        action:'先看原文，再决定是否转化为产品动作或行业卡片。',
        tags:[...new Set([feed.lane,...guessTags(title)])].slice(0,4),
        url:link
      }
    }).filter(Boolean)
  } catch (error) {
    console.warn('[retail-sync] ' + feed.name + ': ' + error.message)
    return []
  }
}

const results = (await Promise.all(FEEDS.map(fetchFeed))).flat()
const seen = new Set()
const fresh = results.filter(item => {
  const key = item.title.toLowerCase().replace(/\s+/g,' ')
  if (seen.has(key)) return false
  seen.add(key)
  return true
})

const fallbackModule = await import(seedFile.href + '?t=' + Date.now())
const fallback = fallbackModule.retailNews.filter(item => !item.id.startsWith('feed-'))
const merged = [...fresh,...fallback].sort((a,b) => String(b.date).localeCompare(String(a.date))).slice(0,60)
const output = '// AUTO-GENERATED by scripts/sync-retail-news.mjs.\n// Sources are refreshed by GitHub Actions; curated stories remain as fallback.\n\nexport const retailNewsLastSyncedAt = ' + JSON.stringify(new Date().toISOString()) + '\n\nexport const retailNews = ' + JSON.stringify(merged,null,2) + '\n'

await mkdir(new URL('../src/data/',import.meta.url),{recursive:true})
await writeFile(seedFile,output,'utf8')
console.log('[retail-sync] synced ' + fresh.length + ' feed stories + ' + fallback.length + ' curated stories = ' + merged.length + ' total')
